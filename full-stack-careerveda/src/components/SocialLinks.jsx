const SocialLinks = ({className = ""}) => {
  const links = socialLinks.filter((link) => ICONS[link.id]);
  // Nothing to show until a URL is pasted into externalLinks.js. Rendering the row
  // regardless would leave an empty strip under the brand.
  if (links.length === 0) return null;

  return (
    <ul className={`social-links ${className}`.trim()}>
      {links.map(({id, label, href}) => (
        <li key={id}>
          <a
            href={href}
            target="_blank"
            rel="noopener noreferrer"
            aria-label={label}
            title={label}
          >
            <svg viewBox="0 0 24 24" aria-hidden="true" focusable="false">
              <path d={ICONS[id]} />
            </svg>
          </a>
        </li>
      ))}
    </ul>
  );
};

