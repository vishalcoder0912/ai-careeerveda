import {chromium} from "playwright";
const browser = await chromium.launch();
const page = await browser.newPage({viewport: {width: 1440, height: 900}});
await page.goto("http://localhost:5173/generative-ai", {waitUntil: "domcontentloaded"}).catch(()=>{});
await page.waitForTimeout(4000);
await page.mouse.move(700, 400);
await page.waitForTimeout(500);
const links = await page.evaluate(() => Array.from(document.querySelectorAll("a[href^='/']")).slice(0,10).map(a => a.getAttribute("href")));
console.log("links:", JSON.stringify(links));
const target = links.find(h => h.startsWith("/programs/")) || links[0];
await page.evaluate((h) => { const a = document.querySelector(`a[href="${h}"]`); a && a.click(); }, target);
await page.waitForTimeout(4000);
const after = await page.evaluate(() => ({ url: location.pathname, cls: document.documentElement.className, bodyCursor: getComputedStyle(document.body).cursor, dot: !!document.querySelector(".ga-cursor-dot"), ring: !!document.querySelector(".ga-cursor-ring") }));
console.log("After client nav to", target, JSON.stringify(after));
await browser.close();
